CREATE TABLE public.sym_trigger (
    trigger_id VARCHAR(128) NOT NULL,
    source_catalog_name VARCHAR(255),
    source_schema_name VARCHAR(255),
    source_table_name VARCHAR(255) NOT NULL,
    channel_id VARCHAR(128) NOT NULL,
    reload_channel_id VARCHAR(128) NOT NULL,
    sync_on_update SMALLINT NOT NULL,
    sync_on_insert SMALLINT NOT NULL,
    sync_on_delete SMALLINT NOT NULL,
    sync_on_incoming_batch SMALLINT NOT NULL,
    name_for_update_trigger VARCHAR(255),
    name_for_insert_trigger VARCHAR(255),
    name_for_delete_trigger VARCHAR(255),
    sync_on_update_condition VARCHAR,
    sync_on_insert_condition VARCHAR,
    sync_on_delete_condition VARCHAR,
    custom_on_update_text VARCHAR,
    custom_on_insert_text VARCHAR,
    external_select VARCHAR,
    tx_id_expression VARCHAR,
    channel_expression VARCHAR,
    excluded_column_names VARCHAR,
    sync_key_names VARCHAR,
    use_stream_lobs SMALLINT NOT NULL,
    use_capture_lobs SMALLINT NOT NULL,
    use_capture_old_data SMALLINT NOT NULL,
    use_handle_key_updates SMALLINT NOT NULL,
    create_time DATETIME,
    last_update_by VARCHAR(50),
    last_update_time DATETIME,
    PRIMARY KEY (trigger_id),
    FOREIGN KEY(channel_id) REFERENCES public.sym_channel (channel_id),
    FOREIGN KEY(reload_channel_id) REFERENCES public.sym_channel (channel_id)
)

