CREATE TABLE transactions (
    ground_id CHAR(32) NOT NULL,
    user_id CHAR(32) NOT NULL,
    created DATETIME NOT NULL,
    amount FLOAT,
    acct_type VARCHAR(255),
    from_wallet_id CHAR(32),
    to_wallet_id CHAR(32),
    reference_id CHAR(32),
    external_id VARCHAR,
    memo VARCHAR(300),
    source_id CHAR(32),
    error VARCHAR,
    state VARCHAR NOT NULL,
    processed_timestamp DATETIME,
    reversed_timestamp DATETIME,
    errored_timestamp DATETIME,
    origin VARCHAR NOT NULL,
    to_snapshot_id CHAR(32),
    from_snapshot_id CHAR(32),
    id CHAR(32) DEFAULT uuid_generate_v4() NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY(ground_id) REFERENCES ground (id),
    FOREIGN KEY(user_id) REFERENCES "user" (id),
    FOREIGN KEY(from_wallet_id) REFERENCES wallet (id),
    FOREIGN KEY(to_wallet_id) REFERENCES wallet (id),
    FOREIGN KEY(reference_id) REFERENCES transactions (id),
    FOREIGN KEY(source_id) REFERENCES transaction_sources (id),
    FOREIGN KEY(to_snapshot_id) REFERENCES snapshot (id),
    FOREIGN KEY(from_snapshot_id) REFERENCES snapshot (id)
)

