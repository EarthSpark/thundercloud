CREATE TABLE reading (
    meter VARCHAR(64),
    heartbeat_start DATETIME,
    heartbeat_end DATETIME,
    kilowatt_hours FLOAT,
    kilowatt_hours_period INTEGER,
    cost FLOAT,
    acct_credit FLOAT,
    acct_plan FLOAT,
    acct_debt FLOAT,
    rate FLOAT,
    tou_modifier FLOAT,
    voltage_min FLOAT,
    voltage_max FLOAT,
    voltage_avg FLOAT,
    power_factor_avg FLOAT,
    true_power_avg FLOAT,
    current_min FLOAT,
    current_max FLOAT,
    current_avg FLOAT,
    frequency FLOAT,
    true_power_inst FLOAT,
    energy FLOAT,
    uptime INTEGER,
    state INTEGER,
    snapshot_id UUID,
    user_power_limit INTEGER,
    apparent_power_avg FLOAT,
    id CHAR(32) DEFAULT uuid_generate_v4() NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT meter_heartbeat_start_unique UNIQUE (meter, heartbeat_start),
    CONSTRAINT meter_heartbeat_end_unique UNIQUE (meter, heartbeat_end)
)

